package threat

import (
	"fmt"
	"net/netip"
	"sort"
	"strings"
)

// RenderNft 把封禁条目渲染成 nftables 文本：table inet router_threat 下有两个集合
// (blocked 为 IPv4、blocked6 为 IPv6)，forward 链对命中集合的源地址 drop。
//
// 安全红线（务必在注释里写清）：
//   - **绝不写 `flush ruleset`**——它会清空内核里所有表，把整台机器的 nft 配置
//     (防火墙、NAT、其它模块) 全部抹掉，这是灾难级事故。
//   - **绝不用 `policy drop`**——我们只 drop 命中集合的流量，默认策略保持 accept，
//     否则一条空集合的误渲染/误清空就会把整机转发流量掐断。
//
// interval 标志是**必需的**：CIDR 条目（如 10.0.0.0/8）依赖 interval 语义才能放进
// 集合里做区间匹配；没有它 nft 会拒绝 CIDR 元素或行为不正确。
func RenderNft(entries []Entry) string {
	var v4, v6 []string
	for _, e := range entries {
		prefix, err := parseEntryPrefix(e.IP)
		if err != nil {
			continue
		}
		if prefix.Addr().Is4() {
			v4 = append(v4, prefix.String())
		} else {
			v6 = append(v6, prefix.String())
		}
	}
	sort.Strings(v4)
	sort.Strings(v6)

	var b strings.Builder
	b.WriteString("table inet router_threat {\n")
	b.WriteString("  set blocked {\n")
	b.WriteString("    type ipv4_addr\n")
	b.WriteString("    flags interval,timeout\n")
	if len(v4) > 0 {
		b.WriteString("    elements = { " + strings.Join(v4, ", ") + " }\n")
	}
	b.WriteString("  }\n")
	b.WriteString("  set blocked6 {\n")
	b.WriteString("    type ipv6_addr\n")
	b.WriteString("    flags interval,timeout\n")
	if len(v6) > 0 {
		b.WriteString("    elements = { " + strings.Join(v6, ", ") + " }\n")
	}
	b.WriteString("  }\n")
	b.WriteString("  chain forward {\n")
	b.WriteString("    type filter hook forward priority filter; policy accept;\n")
	b.WriteString("    ip saddr @blocked drop\n")
	b.WriteString("    ip6 saddr @blocked6 drop\n")
	b.WriteString("  }\n")
	b.WriteString("}\n")
	return b.String()
}

// RenderHostsDeny 生成 /etc/hosts.deny 格式文本。仅包含 IPv4 单 IP 条目；
// CIDR 条目因 hosts.deny（tcp_wrappers）不支持 CIDR，会以注释形式给出提示。
//
// 设计取舍：hosts.deny 是**兜底手段**——它只在有 tcp_wrappers 链接的服务上生效，
// 覆盖远不如 nft 的 forward 链，且对 TCP 之外协议无效。不能把它当作主要防线。
func RenderHostsDeny(entries []Entry) string {
	var b strings.Builder
	b.WriteString("# generated by router-re threat module (fallback, TCP-wrappers only)\n")
	for _, e := range entries {
		// 注释里出现的每个值都必须压成单行。hosts.deny 按行解析，一个带
		// 换行的 IP 能从 "# ..." 里逃出来变成生效规则（例如 "ALL: ALL"
		// 直接拒绝所有连接）。Reason 以前只去掉了 '#'，换行照样能逃逸。
		ipLine := oneLine(e.IP)
		prefix, err := netip.ParsePrefix(ipLine)
		if err != nil {
			// 单 IP：ParsePrefix 失败，退化为 ParseAddr。
			if addr, aerr := netip.ParseAddr(ipLine); aerr == nil && addr.Is4() && !addr.Is4In6() {
				b.WriteString(fmt.Sprintf("ALL: %s # %s\n", addr.String(), oneLine(strings.ReplaceAll(e.Reason, "#", ""))))
				continue
			}
			b.WriteString(fmt.Sprintf("# %s (hosts.deny 不支持该条目: %v)\n", ipLine, sanitizeErr(err)))
			continue
		}
		switch {
		case prefix.Addr().Is4() && prefix.Bits() == 32 && !prefix.Masked().Addr().Is4In6():
			b.WriteString(fmt.Sprintf("ALL: %s # %s\n", prefix.Addr().String(), oneLine(strings.ReplaceAll(e.Reason, "#", ""))))
		case prefix.Addr().Is4():
			b.WriteString(fmt.Sprintf("# %s (hosts.deny 不支持 CIDR，仅 nft 层生效)\n", prefix.String()))
		default:
			b.WriteString(fmt.Sprintf("# %s (hosts.deny 仅 IPv4，跳过)\n", prefix.String()))
		}
	}
	return b.String()
}

// oneLine 把任意字符串压成单行：换行/制表等一律换成空格，其余控制字符丢弃。
func oneLine(s string) string {
	var b strings.Builder
	for _, r := range s {
		switch r {
		case '\r', '\n', '	', '\v', '\f':
			b.WriteByte(' ')
		default:
			if r < 0x20 || r == 0x7f {
				continue
			}
			b.WriteRune(r)
		}
	}
	return b.String()
}

// sanitizeErr 同样压成单行：netip 的错误信息会回显调用方的原始输入。
func sanitizeErr(err error) string {
	if err == nil {
		return ""
	}
	return oneLine(err.Error())
}
