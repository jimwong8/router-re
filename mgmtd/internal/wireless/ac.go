// Package wireless renders hostapd / wpa_supplicant configuration for the
// router's own radio (local AP mode).
//
// It deliberately does NOT implement an AC (Access Controller): managing
// remote access points requires a CAPWAP/vendor protocol and real hardware
// to verify, so that capability was removed rather than shipped as a stub.
package wireless

import (
	"errors"
	"fmt"
	"strings"
)

// SSID is an SSID profile.
type SSID struct {
	Name     string `json:"name"`
	Security string `json:"security"` // "wpa2"/"wpa3"/"open"
	Password string `json:"password"`
	VLAN     int    `json:"vlan"`
	Enabled  bool   `json:"enabled"`
}

// SecurityModes 是唯一允许的取值。
//
// 以前 RenderHostapd 用 switch 的 default 分支兜底成 wpa=0，于是
// Security 传 "WPA2"（大写）或 "wpa-psk" 之类的错值会**静默变成开放网络**：
// 管理端以为开了加密，实际谁都能连。而同一个字段在 RenderWpaSupplicant
// 里又被当成 WPA2 —— 两个渲染器对同一输入给出相反的语义。
var SecurityModes = map[string]bool{"open": true, "wpa2": true, "wpa3": true}

// Validate 校验一个 SSID 配置。
func Validate(s SSID) error {
	if s.Name == "" {
		return errors.New("SSID 名称不能为空")
	}
	// 802.11 规定 SSID 最多 32 字节
	if len(s.Name) > 32 {
		return fmt.Errorf("SSID 名称最多 32 字节，当前 %d", len(s.Name))
	}
	if err := noControl("SSID 名称", s.Name); err != nil {
		return err
	}
	if err := noControl("密码", s.Password); err != nil {
		return err
	}
	sec := s.Security
	if sec == "" {
		sec = "open" // 兼容旧数据：未指定即开放
	}
	if !SecurityModes[sec] {
		return fmt.Errorf("security 只能是 open / wpa2 / wpa3，收到 %q", s.Security)
	}
	if sec != "open" {
		if n := len(s.Password); n < 8 || n > 63 {
			return fmt.Errorf("%s 密码长度必须为 8-63，当前 %d", sec, n)
		}
	}
	if s.VLAN < 0 || s.VLAN > 4094 {
		return fmt.Errorf("VLAN 必须在 0-4094，收到 %d", s.VLAN)
	}
	return nil
}

// noControl 拒绝控制字符：它们会把一行配置拆成两行。
func noControl(field, v string) error {
	for _, r := range v {
		if r < 0x20 || r == 0x7f {
			return fmt.Errorf("%s 不能包含控制字符或换行（发现 %#U）", field, r)
		}
	}
	return nil
}

// oneLine 把任意字符串压成单行，并去掉会破坏 hostapd / wpa_supplicant
// 语法的引号与反斜杠。渲染层兜底用，不依赖调用方跑过 Validate。
func oneLine(s string) string {
	var b strings.Builder
	for _, r := range s {
		switch {
		case r == '	' || r == '\n' || r == '\r' || r == '\v' || r == '\f':
			b.WriteByte(' ')
		case r == '"' || r == '\\':
			// 丢弃：在 wpa_supplicant 的 ssid="..." / psk="..." 里会破坏引号
		case r < 0x20 || r == 0x7f:
			// 丢弃
		default:
			b.WriteRune(r)
		}
	}
	return b.String()
}

// RenderHostapd generates hostapd.conf text for an SSID profile.
func RenderHostapd(ssid SSID) string {
	// 渲染层兜底：名称/密码压成单行。hostapd 配置以行为单位，
	// 密码里一个换行就能追加 "wpa=0" 把加密关掉。
	name := oneLine(ssid.Name)
	pass := oneLine(ssid.Password)
	var b strings.Builder
	b.WriteString("# hostapd.conf generated by router-re mgmtd\n")
	b.WriteString("interface=wlan0\n")
	b.WriteString(fmt.Sprintf("ssid=%s\n", name))
	b.WriteString("hw_mode=g\n")
	b.WriteString("channel=1\n")
	switch ssid.Security {
	case "wpa3":
		b.WriteString("wpa=2\n")
		b.WriteString("rsn_pairwise=CCMP\n")
		b.WriteString("ieee80211w=2\n")
		b.WriteString("wpa_key_mgmt=SAE\n")
		if pass != "" {
			b.WriteString(fmt.Sprintf("wpa_passphrase=%s\n", pass))
		}
	case "wpa2":
		b.WriteString("wpa=2\n")
		b.WriteString("rsn_pairwise=CCMP\n")
		b.WriteString("wpa_key_mgmt=WPA-PSK\n")
		if pass != "" {
			b.WriteString(fmt.Sprintf("wpa_passphrase=%s\n", pass))
		}
	case "open":
		b.WriteString("wpa=0\n")
	default:
		// 失败关闭：未知取值不再回落成 "开放网络"。
		// 宁可 hostapd 起不来（看得见、可排查），也不能静默变成无密码 AP
		// ——那等于把管理端的"已加密"认知直接推翻。
		b.WriteString("wpa=2\n")
		b.WriteString("rsn_pairwise=CCMP\n")
		b.WriteString("wpa_key_mgmt=WPA-PSK\n")
		if pass != "" {
			b.WriteString(fmt.Sprintf("wpa_passphrase=%s\n", pass))
		}
	}
	if ssid.VLAN > 0 {
		b.WriteString(fmt.Sprintf("vlan_id=%d\n", ssid.VLAN))
	}
	return b.String()
}

// RenderWpaSupplicant generates wpa_supplicant.conf text for an SSID profile.
func RenderWpaSupplicant(ssid SSID) string {
	name := oneLine(ssid.Name)
	pass := oneLine(ssid.Password)
	var b strings.Builder
	b.WriteString("# wpa_supplicant.conf generated by router-re mgmtd\n")
	b.WriteString("ctrl_interface=/var/run/wpa_supplicant\n")
	if ssid.Security == "open" {
		b.WriteString("network={\n")
		b.WriteString("\tssid=\"" + name + "\"\n")
		b.WriteString("\tkey_mgmt=NONE\n")
		b.WriteString("}\n")
		return b.String()
	}
	proto := "WPA2"
	keyMgmt := "WPA-PSK"
	if ssid.Security == "wpa3" {
		proto = "WPA3"
		keyMgmt = "SAE"
	}
	b.WriteString("network={\n")
	b.WriteString("\tssid=\"" + name + "\"\n")
	b.WriteString(fmt.Sprintf("\tproto=%s\n", proto))
	b.WriteString(fmt.Sprintf("\tkey_mgmt=%s\n", keyMgmt))
	if pass != "" {
		b.WriteString("\tpsk=\"" + pass + "\"\n")
	}
	b.WriteString("}\n")
	return b.String()
}
