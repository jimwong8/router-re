package wireless

import (
	"fmt"
	"strings"
)

// AP is a managed access point.
type AP struct {
	ID      string   `json:"id"`
	Name    string   `json:"name"`
	MAC     string   `json:"mac"`
	IP      string   `json:"ip"`
	SSIDs   []string `json:"ssids"`
	Channel int      `json:"channel"`
	Online  bool     `json:"online"`
}

// SSID is an SSID profile.
type SSID struct {
	Name     string `json:"name"`
	Security string `json:"security"` // "wpa2"/"wpa3"/"open"
	Password string `json:"password"`
	VLAN     int    `json:"vlan"`
	Enabled  bool   `json:"enabled"`
}

// RenderHostapd generates hostapd.conf text for an SSID profile.
func RenderHostapd(ssid SSID) string {
	var b strings.Builder
	b.WriteString("# hostapd.conf generated by router-re mgmtd\n")
	b.WriteString("interface=wlan0\n")
	b.WriteString(fmt.Sprintf("ssid=%s\n", ssid.Name))
	b.WriteString("hw_mode=g\n")
	b.WriteString("channel=1\n")
	switch ssid.Security {
	case "wpa3":
		b.WriteString("wpa=2\n")
		b.WriteString("rsn_pairwise=CCMP\n")
		b.WriteString("ieee80211w=2\n")
		b.WriteString("wpa_key_mgmt=SAE\n")
		if ssid.Password != "" {
			b.WriteString(fmt.Sprintf("wpa_passphrase=%s\n", ssid.Password))
		}
	case "wpa2":
		b.WriteString("wpa=2\n")
		b.WriteString("rsn_pairwise=CCMP\n")
		b.WriteString("wpa_key_mgmt=WPA-PSK\n")
		if ssid.Password != "" {
			b.WriteString(fmt.Sprintf("wpa_passphrase=%s\n", ssid.Password))
		}
	default: // open
		b.WriteString("wpa=0\n")
	}
	if ssid.VLAN > 0 {
		b.WriteString(fmt.Sprintf("vlan_id=%d\n", ssid.VLAN))
	}
	return b.String()
}

// RenderWpaSupplicant generates wpa_supplicant.conf text for an SSID profile.
func RenderWpaSupplicant(ssid SSID) string {
	var b strings.Builder
	b.WriteString("# wpa_supplicant.conf generated by router-re mgmtd\n")
	b.WriteString("ctrl_interface=/var/run/wpa_supplicant\n")
	if ssid.Security == "open" {
		b.WriteString("network={\n")
		b.WriteString("\tssid=\"" + ssid.Name + "\"\n")
		b.WriteString("\tkey_mgmt=NONE\n")
		b.WriteString("}\n")
		return b.String()
	}
	proto := "WPA2"
	keyMgmt := "WPA-PSK"
	if ssid.Security == "wpa3" {
		proto = "WPA3"
		keyMgmt = "SAE"
	}
	b.WriteString("network={\n")
	b.WriteString("\tssid=\"" + ssid.Name + "\"\n")
	b.WriteString(fmt.Sprintf("\tproto=%s\n", proto))
	b.WriteString(fmt.Sprintf("\tkey_mgmt=%s\n", keyMgmt))
	if ssid.Password != "" {
		b.WriteString("\tpsk=\"" + ssid.Password + "\"\n")
	}
	b.WriteString("}\n")
	return b.String()
}
